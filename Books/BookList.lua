WELCOME TO PARCHMENT READER

Parchment Reader is an in-game library for books, stories, notes, and any other text you want to keep close while playing.

This guide and Adventure Story are starter books. They behave exactly like books you add yourself: you can edit them, move them into collections, rename them, or delete them. Once deleted, a starter book does not return after a reload or addon update.

OPENING AND READING

Left-click a title in the library to open it. Use the previous and next controls in the footer, the mouse wheel, Page Up, or Page Down to move through the text.

The gold progress line in the footer is also interactive. Click or drag along it to travel quickly through a long book. Home offers to move your saved position to the beginning, and End offers to move it to the end.

Parchment Reader remembers the selected book and your reading position across sessions. Text reflows when you resize the window or change the font, so the saved position follows the passage rather than depending only on an old page number.

BOOKMARKS

Open the bookmark control in the footer to save the current passage. Bookmarks can be revisited, renamed, deleted, and restored immediately after an accidental deletion. Each bookmark includes a short preview to help you recognize the saved place.

BUILDING YOUR LIBRARY

Choose Add Book at the bottom of the library to create a book. Give it a title, choose a collection if desired, paste or type the content, and save it.

Right-click any book for its actions. You can edit its title and content or move it to another collection. The Edit Book window also contains Delete. Deleting a book removes its saved reading position and bookmarks after confirmation.

Use the search field to find words in titles or content. The collection selector can show every book or only the books in one collection. Collection actions let you create, rename, and delete collections without losing their books.

QUICK NOTE

Quick Note is a small writing window for capturing text without interrupting the Reader. Saved notes become ordinary books in the Notes collection and can then be edited, moved, or deleted like anything else.

The Reader, Minimize / Restore, and Quick Note shortcuts can be assigned in the addon's Settings or in WoW's native keybinding interface.

WINDOW MODES

Compact Mode hides the library and leaves the reading area visible. Restore the library with the control on the left edge.

Minimize turns the Reader into a small floating parchment icon. Click the icon to restore the same window. Its menu can lock the icon in place after you position it.

The Settings window controls Reader size, font, font size, transparency, the minimap icon, and shortcuts. Off uses the standard background. Always keeps the Reader transparent. Smart restores the background while you interact with the Reader and fades it again while it rests.

HELP AND RECOVERY

Keyboard Help lists the Reader-local keys. Escape closes the topmost Parchment Reader window or popover first, while an editor with unsaved changes asks before discarding them.

Reset to Defaults changes interface settings only. It does not delete your books, collections, bookmarks, or reading progress.

You can now delete this guide, rewrite it as your own reference, or keep it nearby. Open Adventure Story when you want a longer text for trying navigation, bookmarks, resizing, and Compact Mode.
