MOONLIGHT AND SUNFIRE

Chapter One: The Broken Causeway

Lethria heard the bridge fail before she saw it.

Stone groaned beneath the rain, and the old causeway folded into the ravine as if an unseen hand had snapped its spine. She threw herself toward a cedar root and caught it with both hands. Her bow vanished into the mist below. One heartbeat later, someone struck the wall beside her and seized the same root.

He wore crimson and gold beneath a mud-dark cloak. Wet blond hair clung to a face too sharp to mistake, and green light burned in his eyes.

A blood elf.

For a moment neither moved. The root creaked under their combined weight.

"If you reach for that knife," he said, glancing at the blade on her belt, "we shall have a very brief argument."

"If I let go," Lethria replied, "you will have an even briefer fall."

The corner of his mouth lifted despite the danger. Together they climbed, first onto a narrow shelf and then through the broken window of a watchtower abandoned so long ago that moss covered its inner walls.

The storm had separated Lethria from her Sentinel patrol. They had been following thieves who carried a stolen kaldorei relic eastward. The blood elf introduced himself as Caelir Sunweave, a scholar sent to recover an artifact taken from a Reliquary expedition. Each described a silver casket marked with a crescent crossed by a flame.

They were hunting the same object.

Lethria distrusted the coincidence. Caelir distrusted her drawn knife. Outside, blue lightning crawled sideways across the sky, and shapes with lanterns moved along both sides of the ravine.

"Your people?" she asked.

"Not unless they have changed our colors to black while I was away."

The thieves had found them.

There was one path out of the tower: a stair descending beneath the hill. Lethria and Caelir looked at the dark opening, then at one another.

"A temporary truce," he said.

"Until we recover the casket."

"Naturally. After that we may return to disliking each other properly."

They entered the stair as the tower door splintered above them.

Chapter Two: Terms of Survival

The passage had once carried water from the hills. Roots pierced its ceiling, and the storm made the old channels roar. Lethria moved without a lamp. Caelir followed by the pale glow gathered in his palm.

"Put that out," she whispered.

"Then I walk into a wall."

"That would improve your silence."

He closed his hand, but not before she saw him smile.

Their pursuers entered the tunnel behind them. Lethria counted six voices, perhaps seven. She guided Caelir into a side chamber and waited until the first two thieves passed. Her blade stopped beneath one hood. Caelir's spell bound the other in strands of red light before either could cry out.

The captives carried maps bearing seals from both factions, along with orders meant to convince each side that the other had stolen the casket. Someone wanted a battle over the relic.

Caelir translated the arcane notation in the margin. The casket contained two halves of an ancient focus: one attuned to moonlit waters, the other to solar fire. Joined beneath the coming dawn, they could tear open every ley channel beneath the valley.

"The storm is not weather," he said. "It is pressure escaping from the focus."

"And at dawn?"

"The valley burns. Anyone watching will blame whichever army survives."

They could no longer wait for their patrols. The maps led to a ruined observatory beyond the hills, but floodwater blocked the direct tunnel. Their only route climbed through a collapsed shaft barely wide enough for one person.

Caelir went first. Halfway up, the stone beneath Lethria broke. He caught her wrist and held her above the black water while loose rock battered his shoulders.

"You may let go," she gasped. "The casket matters more."

"I have already lost one bridge today," he said through clenched teeth. "I refuse to lose an ally as well."

He pulled until she found a foothold. At the top, Lethria wrapped the cut across his palm with a strip torn from her cloak. His hand was warm in hers. Neither spoke of how long she held it after the knot was tied.

They emerged beneath thinning clouds. Far away, signal fires answered one another: silver-blue in the west, crimson in the east. Both patrols were calling reinforcements.

"By sunrise," Lethria said, "our people may be fighting even if we stop the focus."

"Then we shall have to do two impossible things before breakfast."

Chapter Three: Hunters on Both Roads

They crossed the forest by game trails. Caelir knew the shape of the ley lines; Lethria knew where the land would hide them. Their differences, so sharp in the tower, began to fit together like the two sides of a clasp.

At an abandoned shrine they found Lethria's captain waiting with three Sentinels. Captain Shalara ordered Lethria away from the blood elf and accused Caelir of carrying the stolen focus. A moment later, blood elf riders surrounded the clearing. Their magister made the opposite accusation.

Swords cleared scabbards. Bows rose. Every lie planted by the thieves was ready to flower.

Lethria stepped between the lines.

"The casket is at the observatory," she said. "He saved my life and helped uncover the plot."

Shalara's expression hardened. "Stand aside. Your judgment has been compromised."

Across the clearing, Caelir's magister commanded him to surrender the night elf as a spy. Caelir moved to Lethria's side instead.

"My judgment," he said, "has finally acquired evidence."

No one lowered a weapon.

Then an arrow struck the shrine between them. Black-fletched shafts poured from the trees. The hidden conspirators attacked both patrols at once, wearing pieces of kaldorei and sin'dorei armor so that, in the confusion, every wound would appear to come from an enemy.

Lethria shouted the truth, but battle swallowed words. She and Caelir fought back-to-back. Her borrowed bow found the shadows between trees; his fire illuminated attackers without touching the forest. When Shalara fell beneath a poisoned blade, Caelir crossed the clearing under arrow fire and burned the poison from the wound.

The act broke the lie more effectively than any speech. Sentinels shielded the blood elf while he worked. Blood elf riders drove the assassins from the northern path.

The captured leader finally named his master: Vaelor Duskhand, a former Kirin Tor arcanist who believed another war would leave the valley's relics unguarded. He was already at the observatory.

Shalara was too weak to continue. The magister's horse had been killed, and the skirmish had scattered both patrols. Lethria and Caelir remained the only pair who knew the underground route shown on the stolen maps.

The captains gave them until dawn.

As they left, Shalara caught Lethria's arm. "You trust him?"

Lethria watched Caelir wait at the edge of the clearing, rain shining on his torn cloak.

"With my life," she said.

The answer frightened her less than how easily it came.

Chapter Four: The Chamber Below

The observatory stood inside a ring of dead trees. Its dome had fallen inward, exposing a machine of silver mirrors and golden lenses. At the center, Vaelor Duskhand raised the opened casket over a basin of light.

Moon-pale water circled one half of the focus. The other burned like a small sun. Threads of power ran outward through the floor, feeding the unnatural storm.

Vaelor welcomed them as though they were expected guests.

"Look how readily your people drew weapons," he said. "I offered only a rumor. Hatred did the rest."

"You mistook old wounds for obedience," Caelir replied.

Vaelor closed his fist. The floor split between them.

Lethria rolled beneath a blade of white fire while Caelir shattered a descending mirror with a spell. Reflections multiplied Vaelor across the chamber. Each false image spoke with his voice; each cast a shadow that moved in a different direction.

Lethria stopped searching with her eyes. She listened instead: rain on broken stone, the pulse of the focus, Caelir's breath, and one boot scraping where no reflection stood. Her arrow struck Vaelor's shoulder.

His spell went wild. A wall of force threw Lethria against a pillar. Stone pinned her leg, and her bow slid beyond reach.

Caelir could have seized the casket. Instead he ran to her.

"The focus," she warned.

"I know."

"If dawn reaches it—"

"I know."

He braced both hands beneath the stone. Arcane light trembled around him, but the pillar barely moved. Lethria reached through the dust and placed her hand over his injured palm.

"Together," she said.

Moonlight gathered along her silver tattoos, faint but steady. Caelir's fire answered it. The two powers did not consume one another. They braided, cool and warm, and the broken pillar lifted long enough for her to pull free.

Vaelor stared at them in disbelief. He had built his plan upon the certainty that moon and sun could meet only in destruction.

The first edge of dawn touched the eastern mirrors.

Chapter Five: The Choice at Dawn

The focus awakened.

Every lens in the observatory blazed. Beneath the floor, ley channels opened like cracks in glass. Lethria saw distant trees bend toward the tower. Caelir saw the spell's design and understood its cruel final lock: the two halves could be separated only by bearers willing to take their power into themselves.

One bearer would receive the cold of endless night. The other would receive the heat of an unsetting sun. Either burden could kill.

"There must be another way," Lethria said.

"There is no time to find it."

Caelir reached for the burning half. Lethria caught his wrist.

"You do not decide this alone."

"Nor do you. That is rather the problem."

Even then, with the chamber coming apart around them, he made her laugh. It was only one breath, but it cleared the fear from her mind.

They took the focus together.

Winter entered Lethria's bones. Fire flooded Caelir's veins. Across the joined halves, each felt the other's pain. They also felt everything left unspoken: his wonder when she had trusted him in the clearing; her terror when the pillar fell; the fragile hope both had refused to name.

They turned the power inward, not against one another but toward the empty space between their hands. Moonlight softened the fire. Sunfire warmed the night. The forces spiraled down until the focus became no more than two pieces of dull crystal.

Vaelor lunged for them. The collapsing machine caught him in a cage of his own mirrors. Lethria dragged Caelir through the western arch as the observatory folded into the chamber below.

They woke on a hillside after sunrise. The storm was gone. Drops of water shone on every leaf, each holding a tiny, ordinary sky.

Caelir lay beside her, alive but pale. Lethria touched his cheek. His eyes opened.

"Are we still observing the temporary truce?" he asked.

"No."

His smile faded.

She leaned down and kissed him.

"I believe," she whispered, "we require new terms."

Chapter Six: The Road They Chose

Stopping the focus did not end every difficulty. Truth rarely travels as quickly as suspicion.

Some Sentinels called Lethria reckless. Some blood elves called Caelir disloyal. Their reports were questioned, their motives examined, and their meetings watched. Orders placed them on opposite sides of the valley before the next moon.

For a season they obeyed. They wrote letters carried by neutral merchants and met only where an old stone bridge crossed a quiet stream. Each meeting made the next separation harder.

At last Captain Shalara came to the bridge. The scar of Vaelor's poison still marked her neck.

"The remaining conspirators are using another ruin," she told them. "My patrol cannot enter without provoking the blood elf camp nearby. Their magister has the same problem."

Caelir looked at Lethria. "Two impossible things before breakfast?"

"We have practice."

Their success led to another joint mission, then another. They became envoys no commander admitted to needing and scouts both sides trusted when official trust failed. The work was dangerous, but it gave them something neither faction could offer alone: a road they were allowed to walk together.

Years later, travelers in that valley spoke of a restored watchtower beside a new wooden bridge. A silver crescent hung above one side of its door and a golden flame above the other. Lost soldiers, scholars, merchants, and wanderers could find shelter there without surrendering their colors.

Lethria kept maps on every wall. Caelir kept too many books on every table. They still argued about lamps in dark tunnels. They still disagreed about whether a knife counted as a polite introduction.

But when storms crossed the hills, moonlight shone from one window and warm fire from the next. Those who saw the two lights together knew the bridge ahead was safe.

Their love did not erase the history between their peoples, nor did it heal every wound. It did something smaller and more difficult: it proved that history was not the only future available to them.

And whenever someone asked how a night elf and a blood elf had chosen the same road, Caelir would begin with a broken causeway, a shared root, and a very brief argument.

Lethria always corrected him.

"It began," she would say, taking his hand, "when neither of us let go."

The End.
